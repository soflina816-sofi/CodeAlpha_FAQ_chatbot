import gradio as gr
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

# FAQ questions and their answers
faqs = [
    ("What is artificial intelligence?",
     "Artificial Intelligence (AI) enables computers to perform tasks that normally require human intelligence."),

    ("What is machine learning?",
     "Machine Learning is a branch of AI where computers learn patterns from data."),

    ("What is natural language processing?",
     "Natural Language Processing (NLP) helps computers understand and process human language."),

    ("What is deep learning?",
     "Deep Learning uses neural networks with multiple layers to learn complex patterns."),

    ("What is a chatbot?",
     "A chatbot is a software application that answers users through text or voice."),

    ("What is Python used for in AI?",
     "Python is widely used in AI for data processing, machine learning, deep learning and NLP."),

    ("What is supervised learning?",
     "Supervised learning trains a model using input data and its correct output labels."),

    ("What is computer vision?",
     "Computer vision helps computers analyze and understand images and videos.")
]

questions = [item[0] for item in faqs]

vectorizer = TfidfVectorizer(
    lowercase=True,
    stop_words="english",
    ngram_range=(1, 2)
)

faq_vectors = vectorizer.fit_transform(questions)

def chatbot(user_question):
    if not user_question.strip():
        return "Please enter a question."

    user_vector = vectorizer.transform([user_question])
    scores = cosine_similarity(user_vector, faq_vectors)[0]

    best_index = scores.argmax()
    best_score = scores[best_index]

    if best_score < 0.12:
        return "Sorry, I couldn't find a matching FAQ. Please try another question."

    return faqs[best_index][1]

app = gr.Interface(
    fn=chatbot,
    inputs=gr.Textbox(
        label="Ask your question",
        placeholder="Example: What is machine learning?"
    ),
    outputs=gr.Textbox(label="Chatbot Answer"),
    title="CodeAlpha AI FAQ Chatbot",
    description="Ask questions about Artificial Intelligence and related topics."
)

app.launch(share=True)